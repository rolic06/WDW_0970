# A column of daily sales
sales = [500, 1200, 800, 2500, 300]

print("All sales:", sales)
print("First day sale:", sales[0]) 
print("second day sales", sales[1])    # Python starts counting at 0!
print("Total days:", len(sales))       # Counts how many items are in the list
print("Total sales:", sum(sales))      # Adds all numbers together
print("Highest sale:", max(sales))     # Finds the biggest number
